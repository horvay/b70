#!/usr/bin/env python3
"""Generate src/io/unicode_tables.hpp for the native tokenizer from Python's unicodedata (stdlib only, CPU).

    python3 -I tools/gen_unicode.py > src/io/unicode_tables.hpp

Tables: \\p{L} and \\p{N} as sorted code point ranges (for byte-level BPE pre-tokenizer regexes), and what NFC needs:
canonical combining classes, full canonical decompositions (Hangul syllables are algorithmic and not listed), and
the primary composites (pairs that NFC recomposes, i.e. canonical pairs that are not composition exclusions).
"""
import sys
import unicodedata as ud

MAX = 0x110000


def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def is_hangul_syllable(cp):
    return 0xAC00 <= cp <= 0xD7A3


def canon_decomp(cp):
    d = ud.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return None
    return [int(x, 16) for x in d.split()]


def full_decomp(cp):
    d = canon_decomp(cp)
    if d is None:
        return [cp]
    out = []
    for x in d:
        out += full_decomp(x)
    return out


def main():
    cat = lambda cp: ud.category(chr(cp))
    L = ranges(lambda cp: cat(cp)[0] == "L")
    N = ranges(lambda cp: cat(cp)[0] == "N")
    ccc = [(cp, ud.combining(chr(cp))) for cp in range(MAX) if ud.combining(chr(cp))]
    dec = []
    comp = []
    for cp in range(MAX):
        if is_hangul_syllable(cp):
            continue
        d = canon_decomp(cp)
        if d is None:
            continue
        dec.append((cp, full_decomp(cp)))
        # Primary composite: a two-character canonical decomposition that NFC puts back together.
        if len(d) == 2 and ud.normalize("NFC", chr(d[0]) + chr(d[1])) == chr(cp):
            comp.append((d[0], d[1], cp))
    w = sys.stdout.write
    w("// Generated by tools/gen_unicode.py from Python's unicodedata %s. Do not edit.\n" % ud.unidata_version)
    w("#pragma once\n#include <cstdint>\nnamespace uni {\n")
    w("struct Range { uint32_t a, b; };\n")
    for name, rs in (("LETTER", L), ("NUMBER", N)):
        w("inline constexpr Range %s[] = {\n" % name)
        for i in range(0, len(rs), 6):
            w("    " + " ".join("{0x%X, 0x%X}," % r for r in rs[i:i + 6]) + "\n")
        w("};\n")
    w("struct CCC { uint32_t cp; uint8_t c; };\ninline constexpr CCC COMBINING[] = {\n")
    for i in range(0, len(ccc), 8):
        w("    " + " ".join("{0x%X, %d}," % x for x in ccc[i:i + 8]) + "\n")
    w("};\n")
    # Decompositions: index table into one flat array.
    flat, idx = [], []
    for cp, d in dec:
        idx.append((cp, len(flat), len(d))); flat += d
    w("inline constexpr uint32_t DECOMP_DATA[] = {\n")
    for i in range(0, len(flat), 12):
        w("    " + " ".join("0x%X," % x for x in flat[i:i + 12]) + "\n")
    w("};\nstruct Decomp { uint32_t cp; uint16_t off; uint8_t len; };\ninline constexpr Decomp DECOMP[] = {\n")
    for i in range(0, len(idx), 6):
        w("    " + " ".join("{0x%X, %d, %d}," % x for x in idx[i:i + 6]) + "\n")
    w("};\nstruct Comp { uint32_t a, b, c; };\ninline constexpr Comp COMPOSE[] = {\n")
    comp.sort()
    for i in range(0, len(comp), 6):
        w("    " + " ".join("{0x%X, 0x%X, 0x%X}," % x for x in comp[i:i + 6]) + "\n")
    w("};\n} // namespace uni\n")


if __name__ == "__main__":
    main()
